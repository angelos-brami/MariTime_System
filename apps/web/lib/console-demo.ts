export function demoWorkspaceFor(eventId: string): EventWorkspaceData | null {
  const event = demoOpenEvents.find((candidate) => candidate.id === eventId);
  if (!event) return null;
  if (event.id === demoWorkspace.id) return demoWorkspace;
  return {
    ...demoWorkspace,
    id: event.id,
    slug: event.slug,
    event_type: event.event_type,
    corridor: event.corridor,
    status: event.status,
    severity: event.severity,
    title: event.title,
    claims: [],
    sources: [],
    versions: [],
  };
}

